import assert from 'node:assert/strict';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
const { chromium } = await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE).href);
const ROOT = 'http://127.0.0.1:4317';
const DIR = 'pruefberichte/browser';
await mkdir(DIR, { recursive: true });
const browser = await chromium.launch({ headless: true });
const results = [], errors = [];
let desktop, mobile;
const record = (name) => { results.push({ name, passed: true }); console.log('PASS', name); };
async function screenshot(page, name) { await page.screenshot({ path: `${DIR}/${name}.png`, fullPage: true }); }
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce', acceptDownloads: true });
  desktop = await context.newPage();
  desktop.on('pageerror', (e) => errors.push({ page: 'desktop', message: e.message }));
  assert.equal((await desktop.goto(ROOT, { waitUntil: 'networkidle' })).status(), 200);
  await desktop.locator('.startup-splash').waitFor({ state: 'hidden', timeout: 15000 });
  assert.match(await desktop.title(), /Aufmaß Pro/);
  assert.ok(await desktop.getByRole('button', { name: 'PDF-Dateien auswählen' }).isVisible());
  await screenshot(desktop, 'Original-Desktop-Start');
  record('Original-Desktopseite interaktiv geladen');
  const mobileContext = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1, reducedMotion: 'reduce', acceptDownloads: true });
  mobile = await mobileContext.newPage();
  mobile.on('pageerror', (e) => errors.push({ page: 'mobil', message: e.message }));
  assert.equal((await mobile.goto(`${ROOT}/mobil`, { waitUntil: 'networkidle' })).status(), 200);
  await mobile.getByRole('heading', { name: 'Projekt vorbereiten' }).waitFor();
  await mobile.waitForTimeout(2200);
  await screenshot(mobile, 'Original-Mobil-Start');
  const title = 'Pruefung Original V45';
  const field = (text) => mobile.locator('label').filter({ hasText: text }).locator('input').first();
  assert.equal(await mobile.getByPlaceholder('z. B. Wohnhaus Müller').inputValue(), '');
  await mobile.getByPlaceholder('z. B. Wohnhaus Müller').fill(title);
  await mobile.getByPlaceholder('Name oder Architekturbüro').fill('Kuenstlicher Testkunde');
  await mobile.getByRole('button', { name: 'Räume aufnehmen' }).click();
  await field(/^Raumbezeichnung/).fill('Pruefraum 5 x 4');
  await field(/^Länge/).fill('5');
  await field(/^Breite/).fill('4');
  await field(/^Höhe/).fill('2,5');
  await field(/^Anzahl/).fill('1');
  for (const name of ['Wände', 'Decke', 'Boden', 'Fußleisten']) await mobile.getByRole('button', { name, exact: true }).click();
  assert.match(await mobile.locator('.mobile-room-preview').innerText(), /45,00/);
  assert.match(await mobile.locator('.mobile-room-preview').innerText(), /20,00/);
  await mobile.getByRole('button', { name: 'Raum hinzufügen', exact: true }).click();
  await mobile.locator('.mobile-room-list').getByText('Pruefraum 5 x 4').waitFor();
  record('Raum ueber Originalformular aufgenommen: 5 x 4 x 2,5 m');
  await mobile.getByRole('navigation', { name: 'Bereiche' }).getByRole('button', { name: 'PC', exact: true }).click();
  const totals = await mobile.locator('.mobile-total-grid').innerText();
  assert.match(totals, /45,00/); assert.match(totals, /20,00/); assert.match(totals, /18,00/);
  await mobile.getByRole('button', { name: 'Speichern & an PC übertragen', exact: true }).click();
  await mobile.locator('.mobile-ready').waitFor({ timeout: 20000 });
  await screenshot(mobile, 'Original-Mobil-Gespeichert');
  record('Original-Speicherablauf Browser -> Projekt-API -> lokale SQLite-Datenbank');
  const list = await (await mobile.request.get(`${ROOT}/api/projects`)).json();
  const summary = list.projects.find((p) => p.title === title);
  assert.ok(summary); assert.equal(summary.positionCount, 1);
  const stored = await (await mobile.request.get(`${ROOT}/api/projects/${summary.id}`)).json();
  assert.equal(stored.state.measurements.length, 1);
  assert.equal(stored.state.measurements[0].areaOverride, 20);
  assert.equal(stored.state.measurements[0].perimeterOverride, 18);
  assert.equal(stored.state.meta.vobRuleConfirmed, false);
  await writeFile(`${DIR}/gespeichertes-testprojekt.json`, JSON.stringify(stored, null, 2));
  record('Gespeicherten Originalraum und unveraenderten VOB-Pruefstatus nachgelesen');
  await mobile.getByRole('navigation', { name: 'Bereiche' }).getByRole('button', { name: /Prüfen/ }).click();
  const downloadEvent = mobile.waitForEvent('download');
  await mobile.getByRole('button', { name: /Handwerker-App/ }).click();
  const download = await downloadEvent;
  await download.saveAs(`${DIR}/original-json-export.json`);
  const exported = JSON.parse(await readFile(`${DIR}/original-json-export.json`, 'utf8'));
  assert.deepEqual(exported.quantities.map((q) => q.quantity).sort((a, b) => a - b), [18, 20, 20, 45]);
  record('Original-JSON-Export im Browser heruntergeladen und Mengen geprueft');
  await desktop.reload({ waitUntil: 'networkidle' });
  await desktop.locator('.startup-splash').waitFor({ state: 'hidden', timeout: 15000 });
  await desktop.getByTitle('Gespeicherte Projekte öffnen').click();
  const card = desktop.locator('.project-library-card').filter({ hasText: title });
  await card.getByRole('button', { name: 'Öffnen', exact: true }).click();
  await desktop.waitForTimeout(1800);
  assert.match(await desktop.locator('body').innerText(), /Pruefraum 5 x 4/);
  assert.match(await desktop.locator('body').innerText(), /45,00/);
  await screenshot(desktop, 'Original-Desktop-Mit-Aufmass');
  record('Mobil erfasstes Projekt im Original-Desktopprogramm geoeffnet');
  assert.deepEqual(errors, []);
  record('Keine JavaScript-Seitenfehler im geprueften Ablauf');
  const hostile = await fetch(`${ROOT}/api/projects`, { headers: { Origin: 'https://fremde-seite.example' } });
  assert.equal(hostile.status, 403);
  record('Fremder Webseiten-Ursprung wird im lokalen Starter blockiert');
} catch (error) {
  await writeFile(`${DIR}/fehler.txt`, error.stack ?? String(error));
  if (desktop) await screenshot(desktop, 'Fehler-Desktop').catch(() => {});
  if (mobile) await screenshot(mobile, 'Fehler-Mobil').catch(() => {});
  process.exitCode = 1;
} finally {
  await writeFile(`${DIR}/ergebnis.json`, JSON.stringify({ results, errors, success: !process.exitCode, actualHardwareTested: false }, null, 2));
  await browser.close();
}
